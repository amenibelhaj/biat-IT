/*
 * Fixes the row-collapsing bug in the Excel import.
 *
 * The BIAT network extract is anonymised: every row is named
 * "Routeur AGENCE XX", the asset-number and serial-number columns are
 * empty, and the IP addresses are masked down to four distinct values.
 * The import built each asset's unique key from name + IP, so 18 rows
 * sharing 172.XX.100.XX were treated as one device updated 18 times —
 * 21 rows became 4 assets.
 *
 * Rows without a real identifier are now keyed by their position in the
 * file as well, so every row is preserved, and the import reports how
 * many rows had no identifier of their own.
 *
 * Save in the PROJECT ROOT and run:   node fixrows.js
 * Then re-import your file using "Remplacer l'inventaire existant".
 */

